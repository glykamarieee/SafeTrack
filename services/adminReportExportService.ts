import * as Print from "expo-print";
import * as Sharing from "expo-sharing";
import * as FileSystem from "expo-file-system/legacy";
import type { AdminReportSummary } from "./adminService";

function escapeHtml(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function escapeCsv(value: string | number) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function formatRange(startDate: string, endDate: string) {
  const formatter = new Intl.DateTimeFormat("en-PH", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });

  return `${formatter.format(
    new Date(`${startDate}T12:00:00`)
  )} to ${formatter.format(new Date(`${endDate}T12:00:00`))}`;
}

function getRows(summary: AdminReportSummary) {
  return [
    ["Guardian Accounts", summary.guardianAccounts],
    ["Registered Children", summary.registeredChildren],
    ["Smartwatch Devices", summary.smartwatchDevices],
    ["Location Records", summary.locationRecords],
    ["Safe-Zone Events", summary.safeZoneEvents],
    ["SOS Records", summary.sosRecords],
  ] as const;
}

async function shareFile(
  uri: string,
  mimeType: string,
  title: string
) {
  const canShare = await Sharing.isAvailableAsync();

  if (!canShare) {
    throw new Error("File sharing is unavailable on this device.");
  }

  await Sharing.shareAsync(uri, {
    mimeType,
    dialogTitle: title,
  });
}

