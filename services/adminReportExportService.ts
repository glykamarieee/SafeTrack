export async function exportAdminSummaryCsv(
  summary: AdminReportSummary,
  startDate: string,
  endDate: string
) {
  const cacheDirectory = FileSystem.cacheDirectory;

  if (!cacheDirectory) {
    throw new Error("SafeTrack could not access temporary file storage.");
  }

  const rows = [
    ["SafeTrack Administrative Summary"],
    [`Selected Period: ${formatRange(startDate, endDate)}`],
    [],
    ["Record Type", "Total"],
    ...getRows(summary),
  ];

  const csv = rows
    .map((row) => row.map((value) => escapeCsv(value)).join(","))
    .join("\n");

  const filename = `SafeTrack_Admin_Report_${startDate.replaceAll(
    "-",
    ""
  )}_${endDate.replaceAll("-", "")}.csv`;

  const uri = `${cacheDirectory}${filename}`;

  await FileSystem.writeAsStringAsync(uri, csv, {
    encoding: FileSystem.EncodingType.UTF8,
  });

  await shareFile(
    uri,
    "text/csv",
    "Export SafeTrack Excel-Compatible CSV"
  );
}